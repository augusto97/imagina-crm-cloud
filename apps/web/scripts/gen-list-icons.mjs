const seen = new Set();
const missing = [];
const out = [];
for (const [category, items] of Object.entries(CATALOG)) {
    for (const [key, file, label] of items) {
        if (seen.has(key)) throw new Error(`Clave duplicada: ${key}`);
        seen.add(key);
        const path = join(ASSETS, `${file}-fill.svg`);
        if (!existsSync(path)) {
            missing.push(`${key} → ${file}`);
            continue;
        }
        const svg = readFileSync(path, 'utf8');
        const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
        if (ds.length === 0) throw new Error(`Sin <path d> en ${file}`);
        out.push({ key, label, category, d: ds.join(' ') });
    }
}
if (missing.length > 0) {
    console.error('Iconos no encontrados en Phosphor:\n  ' + missing.join('\n  '));
    process.exit(1);
}

const lines = [
    '// GENERADO por scripts/gen-list-icons.mjs — no editar a mano.',
    '// Fuente: @phosphor-icons/core (MIT), peso "fill", viewBox 0 0 256 256.',
    'export interface ListIconPath { key: string; label: string; category: string; d: string }',
    'export const LIST_ICON_PATHS: readonly ListIconPath[] = [',
    ...out.map((o) => `    { key: ${JSON.stringify(o.key)}, label: ${JSON.stringify(o.label)}, category: ${JSON.stringify(o.category)}, d: ${JSON.stringify(o.d)} },`),
    '];',
    '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`${out.length} iconos → ${OUT}`);
