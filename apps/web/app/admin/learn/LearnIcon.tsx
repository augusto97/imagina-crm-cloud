export function LearnIcon({ name, className }: { name: string | undefined; className?: string }): JSX.Element {
    const Icon = (name && LEARN_ICONS[name]) || BookOpen;
    return <Icon className={className} aria-hidden />;
}

const TONE_BG: Record<string, string> = {
    cyan: 'hsl(var(--imcrm-tone-cyan))',
    mint: 'hsl(var(--imcrm-tone-mint))',
    rose: 'hsl(var(--imcrm-tone-rose))',
    blue: 'hsl(var(--imcrm-tone-blue))',
    violet: 'hsl(var(--imcrm-tone-violet))',
    amber: 'hsl(var(--imcrm-tone-amber))',
    slate: 'hsl(var(--imcrm-tone-slate))',
};

/** Ícono en un cuadrado del color del módulo. */
export function ToneSquare({ icon, tone, size = 28 }: { icon: string; tone: string; size?: number }): JSX.Element {
    return (
        <span
            className="imcrm-inline-flex imcrm-shrink-0 imcrm-items-center imcrm-justify-center imcrm-rounded-lg imcrm-text-white imcrm-shadow-sm"
            style={{ width: size, height: size, background: TONE_BG[tone] ?? TONE_BG.violet }}
        >
            <LearnIcon name={icon} className={size >= 36 ? 'imcrm-h-5 imcrm-w-5' : 'imcrm-h-4 imcrm-w-4'} />
        </span>
    );
}

export function toneColor(tone: string, alpha = 1): string {
    const base = TONE_BG[tone] ?? TONE_BG.violet!;
    return alpha === 1 ? base : base.replace(')', ` / ${alpha})`);
}
